export function getSimilarListings(id: string): Property[] {
  const listing = getListingById(id);
  if (!listing || !listing.similarIds) return [];
  return listing.similarIds
    .map((sid) => getListingById(sid))
    .filter((l): l is Property => l !== undefined);
}
